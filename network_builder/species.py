"""Species enumeration and rdkit 3D template generation.

Scope: C2-and-below C/H/O adsorbates plus the gas reference molecules demanded
by the Fe5C2(510) Fischer-Tropsch campaign (parent manifest, 2026-09-21).

Template contract (verified against the cluster gold standard
``$R/recnet-runs/ft2dpv22-demo-S/prepared_data/ads_templates/*.xyz``):

* plain extxyz, exactly what ``ase.io.write(..., format="extxyz")`` emits:
  line 1 = atom count, line 2 = ``Properties=species:S:1:pos:R:3 pbc="F F F"``,
  then ``symbol x y z`` with 8 decimals -- **no cell, no extra columns**;
* atom order is the rdkit atom order (heavy atoms first, hydrogens appended by
  ``Chem.AddHs``) so that ``ad_idx`` and ``broken_bond`` are stable indices into
  the template that ``handlers/ts.py`` reads with ``ase.io.read``.

Geometry is generated by ETKDGv3 with a fixed seed (deterministic for a pinned
rdkit version; the version is recorded in ``MANIFEST.json``).
"""

