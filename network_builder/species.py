# ---------------------------------------------------------------------------
# Graph identity
# ---------------------------------------------------------------------------


def identity_key(symbols: Sequence[str], edges: Iterable[Tuple[int, int]]) -> str:
    """Order-agnostic canonical key for an H-explicit connectivity graph.

    Bond orders are deliberately excluded: ``handlers/context.py`` and
    ``handlers/ts.py`` detect bonds from interatomic distances only (covalent
    radii x 1.2), so bond order never reaches the pipeline. Hydrogen atoms are
    explicit graph nodes, which is what separates isomers such as HCO (H on C)
    from COH (H on O), or CCH2 from CHCH.
    """
    symbols = tuple(symbols)
    edge_set = {tuple(sorted((int(i), int(j)))) for i, j in edges}
    n = len(symbols)
    adjacency: List[List[int]] = [[] for _ in range(n)]
    for i, j in sorted(edge_set):
        adjacency[i].append(j)
        adjacency[j].append(i)

    colors = list(symbols)
    for _ in range(max(1, n)):
        signature = [
            colors[i] + "(" + "".join(sorted(colors[j] for j in adjacency[i])) + ")"
            for i in range(n)
        ]
        ranks = {value: rank for rank, value in enumerate(sorted(set(signature)))}
        colors = [str(ranks[value]) for value in signature]

    labels = [f"{symbols[i]}:{colors[i]}" for i in range(n)]
    node_part = ",".join(sorted(labels))
    edge_part = ",".join(
        sorted("-".join(sorted((labels[i], labels[j]))) for i, j in sorted(edge_set))
    )
    return f"N[{node_part}]E[{edge_part}]"


def fragment_identity(symbols: Sequence[str], edges: Iterable[Tuple[int, int]],
                      keep: Sequence[int]) -> str:
    """Identity of the sub-graph induced by ``keep`` (relabelled 0..k-1)."""
    keep = list(keep)
    local = {atom: idx for idx, atom in enumerate(keep)}
    sub_symbols = [symbols[atom] for atom in keep]
    sub_edges = [
        (local[i], local[j])
        for i, j in edges
        if i in local and j in local
    ]
    return identity_key(sub_symbols, sub_edges)


def split_fragments(n: int, edges: Iterable[Tuple[int, int]], cut: Tuple[int, int]):
    """Connected components after removing the ``cut`` edge."""
    adjacency: List[List[int]] = [[] for _ in range(n)]
    for i, j in edges:
        if tuple(sorted((i, j))) == tuple(sorted(cut)):
            continue
        adjacency[i].append(j)
        adjacency[j].append(i)

    seen = set()
    components: List[List[int]] = []
    for start in range(n):
        if start in seen:
            continue
        stack = [start]
        seen.add(start)
        comp = []
        while stack:
            node = stack.pop()
            comp.append(node)
            for neighbor in adjacency[node]:
                if neighbor not in seen:
                    seen.add(neighbor)
                    stack.append(neighbor)
        components.append(sorted(comp))
    return sorted(components)


