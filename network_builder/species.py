def _rdkit_mol(smiles: str) -> Chem.Mol:
    mol = Chem.MolFromSmiles(smiles)
    if mol is None:
        raise ValueError(f"rdkit could not parse SMILES {smiles!r}")
    return Chem.AddHs(mol)


def _embed(mol: Chem.Mol, seed: int) -> np.ndarray:
    """Deterministic 3D coordinates; single atoms sit at the origin."""
    n = mol.GetNumAtoms()
    if n == 1:
        return np.zeros((1, 3))
    params = AllChem.ETKDGv3()
    params.randomSeed = seed
    conf_id = AllChem.EmbedMolecule(mol, params)
    if conf_id < 0:
        params.useRandomCoords = True
        conf_id = AllChem.EmbedMolecule(mol, params)
    if conf_id < 0:
        raise RuntimeError(f"rdkit ETKDG failed to embed {Chem.MolToSmiles(mol)!r}")
    return np.array(mol.GetConformer(conf_id).GetPositions(), dtype=float)


def _materialise(spec: SpeciesSpec, seed: int) -> Species:
    mol = _rdkit_mol(spec.smiles)
    positions = _embed(mol, seed)
    symbols = tuple(atom.GetSymbol() for atom in mol.GetAtoms())
    bonds = tuple(
        (bond.GetBeginAtomIdx(), bond.GetEndAtomIdx(), float(bond.GetBondTypeAsDouble()))
        for bond in mol.GetBonds()
    )

    counts: Dict[str, int] = {}
    for symbol in symbols:
        counts[symbol] = counts.get(symbol, 0) + 1

    # Cross-check three independent sources: the declared spec formula, rdkit's
    # perception of the SMILES, and the element counts of the embedded atoms.
    formula_rdkit = rdMolDescriptors.CalcMolFormula(mol)
    formula_from_graph = "".join(
        f"{s}{counts[s]}" if counts[s] != 1 else s
        for s in sorted(counts, key=lambda s: (s != "C", s != "H", s))
    )
    for label, value in (("rdkit", formula_rdkit), ("atoms", formula_from_graph)):
        if value != spec.formula:
            raise AssertionError(
                f"{spec.key}: declared formula {spec.formula} != {label} formula {value} "
                f"(SMILES {spec.smiles!r})"
            )

    ad_idx = tuple(int(i) for i in spec.ad_idx)
    has_heavy_atom = any(symbol != "H" for symbol in symbols)
    for idx in ad_idx:
        if not 0 <= idx < len(symbols):
            raise AssertionError(f"{spec.key}: ad_idx {idx} out of range")
        # Adsorption anchors must be heavy atoms; the atomic-H adsorbate is the
        # documented exception because it has no heavy atom at all.
        if symbols[idx] == "H" and has_heavy_atom:
            raise AssertionError(f"{spec.key}: ad_idx {idx} points at hydrogen")
    if sorted(set(ad_idx)) != sorted(ad_idx):
        raise AssertionError(f"{spec.key}: ad_idx has duplicates: {ad_idx}")

    # Centre the anchor atoms (or the whole molecule for gas entries) on the
    # origin so that the pipeline's site translation starts from a defined pose.
    centre = positions[list(ad_idx)].mean(axis=0) if ad_idx else positions.mean(axis=0)
    positions = positions - centre

    identity = identity_key(symbols, [(i, j) for i, j, _ in bonds])
    return Species(
        key=spec.key,
        name=spec.name,
        group=spec.group,
        smiles=spec.smiles,
        source=spec.source,
        note=spec.note,
        symbols=symbols,
        positions=tuple(tuple(float(value) for value in row) for row in positions),
        ad_idx=ad_idx,
        bonds=bonds,
        identity=identity,
        counts=counts,
    )


def build_species_table(seed: int = SEED, expansion: bool = False,
                        expansion2: bool = False, expansion3: bool = False,
                        expansion4: bool = False, expansion5: bool = False,
                        expansion6: bool = False,
                        expansion6_tier: str = "closed-shell") -> List[Species]:
    """Materialise every declared species in declaration order.

    ``expansion=True`` appends the closure-round-1 species table
    (:mod:`network_builder.expansion`) **after** the frozen 29 entries, so
    ``sp_xxx`` ids of the frozen table do not move. Default ``False`` keeps the
    frozen dataset byte-identical.

    ``expansion6=True`` appends the C3 closure gaps (:mod:`network_builder.expansion6`,
    2026-09-26 R309) — again **after** everything else, and gated by
    ``expansion6_tier`` (default ``"closed-shell"``, the chemically clean tier;
    ``"all"`` includes doubly-dangling species that still need chemical review).
    """
    specs = tuple(SPECS)
    if expansion or expansion2 or expansion3 or expansion4:
        # 局部导入：默认路径不引入扩展依赖
        from .expansion import EXPANSION_SPECS

        specs = specs + tuple(EXPANSION_SPECS)
    if expansion2:
        from .expansion2 import EXPANSION2_SPECS

        specs = specs + tuple(EXPANSION2_SPECS)
    if expansion3:
        from .expansion3 import EXPANSION3_SPECS

        specs = specs + tuple(EXPANSION3_SPECS)
    if expansion4:
        # 2026-09-25 (R175): closure-completion round — the 7 residual products found by the
        # wave-4 (option c) audit (network_builder/expansion4.py).
        from .expansion4 import EXPANSION4_SPECS

        specs = specs + tuple(EXPANSION4_SPECS)
    if expansion5:
        # 2026-09-25 (R226): scission-residue round — CO2 (gas), the only clean closed-shell
        # fragment of the 76 dropped cuts (network_builder/expansion5.py).
        from .expansion5 import EXPANSION5_SPECS

        specs = specs + tuple(EXPANSION5_SPECS)
    if expansion6:
        # 2026-09-26 (R309): C3 扩网 wave-1 —— 由 closure_audit --max-c 3 机械给出的 C3 缺口，
        # 按档取子集（默认 closed-shell；all 档含双悬挂价物种，需化学评审）。
        from .expansion6 import specs_for_tier

        specs = specs + tuple(specs_for_tier(expansion6_tier))
    return [_materialise(spec, seed) for spec in specs]


def template_text(species: Species) -> str:
    """extxyz text for one template, byte-compatible with the gold standard."""
    atoms = Atoms(
        symbols="".join(species.symbols),
        positions=np.array(species.positions, dtype=float),
        pbc=False,
    )
    buffer = io.StringIO()
    ase_write(buffer, atoms, format="extxyz")
    return buffer.getvalue()
