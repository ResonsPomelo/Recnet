@dataclass(frozen=True)
class SpeciesSpec:
    """Declarative species definition.

    ``ad_idx`` is *specified*, never inferred from geometry: it lists the
    template atom indices that anchor the species to a surface site
    (``handlers/context.py::_build_site_and_center_anchors``). Gas entries use
    an empty ``ad_idx``, which ``handlers/energy.py`` reads as "gas-capable".

    ``formula`` is the *independently declared* Hill formula. It is asserted
    against the rdkit-sensitive parse, which catches the classic SMILES trap:
    an unbracketed ``O`` with one bond silently picks up an implicit hydrogen
    (``[CH3]O`` parses as methanol, not methoxy).
    """

    key: str
    name: str
    group: str  # c1_ads | c2_ads | gas | closure
    smiles: str
    ad_idx: Tuple[int, ...]
    source: str  # manifest-required | closure (added by us)
    formula: str
    note: str = ""


@dataclass(frozen=True)
class Species:
    """A materialised species: template atoms plus graph metadata."""

    key: str
    name: str
    group: str
    smiles: str
    source: str
    note: str
    symbols: Tuple[str, ...]
    positions: Tuple[Tuple[float, float, float], ...]
    ad_idx: Tuple[int, ...]
    #: (i, j, bond_order) over template atom indices
    bonds: Tuple[Tuple[int, int, float], ...]
    identity: str
    counts: Dict[str, int] = field(default_factory=dict)

    @property
    def natoms(self) -> int:
        return len(self.symbols)

    @property
    def is_gas(self) -> bool:
        return len(self.ad_idx) == 0

    @property
    def formula(self) -> str:
        """Hill-order formula, e.g. ``C2H4`` / ``CH2O``."""
        order = [s for s in ("C", "H") if s in self.counts]
        order += sorted(s for s in self.counts if s not in order)
        return "".join(
            f"{s}{self.counts[s]}" if self.counts[s] != 1 else s for s in order
        )

    @property
    def edges(self) -> Tuple[Tuple[int, int], ...]:
        """Bond connectivity ignoring bond order (order is metadata only)."""
        return tuple((i, j) for i, j, _ in self.bonds)


